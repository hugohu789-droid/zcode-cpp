# Regenerates data/dictionary.tsv from the Java original's own SQL dump.
#
#   python tools/extract_dictionary.py                  # ../ime-java/ime.sql
#   python tools/extract_dictionary.py path/to/ime.sql
#
# Reading the dump rather than a running MySQL keeps the data reproducible
# from the sources alone: no database, no credentials, no server version to
# agree on. The dump is one single-row INSERT per line, which is why a line
# scanner is enough and no SQL parser is needed; the script fails loudly if
# that ever stops being true.
#
# Only words with frequency > 44 are kept. That is not a judgement call: it
# is InputMethodService.FREQUENCY_BOUND, and the service's own queries are
# `where frequency > #{gtFrequency}`, so these 38,743 rows are the entire
# dictionary it ever loads. The other 461,182 rows are never read.
#
# `length` is not written out. It is a column in the table, but it equals the
# string's length for every one of the 499,925 rows (checked), so storing it
# would only create something that can disagree with itself.

import io
import os
import re
import sys

FREQUENCY_BOUND = 44

# INSERT INTO `word` VALUES (1, 'xxx', 9, 1255);
ROW = re.compile(r"^INSERT INTO `word` VALUES \((\d+), '(.*)', (\d+), (\d+)\);$")

TAB = chr(9)
NL = chr(10)
BACKSLASH = chr(92)


def unquote(text):
    """MySQL's string escaping, as Navicat writes it."""
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch != BACKSLASH or i + 1 >= len(text):
            out.append(ch)
            i += 1
            continue
        nxt = text[i + 1]
        out.append({'n': NL, 't': TAB, 'r': chr(13), '0': chr(0),
                    'b': chr(8), 'Z': chr(26)}.get(nxt, nxt))
        i += 2
    return ''.join(out)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if src is None:
        src = os.path.join(os.path.dirname(here), 'ime-java', 'ime.sql')
    if not os.path.exists(src):
        sys.stderr.write('no such file: %s\n' % src)
        return 1
    out_path = os.path.join(here, 'data', 'dictionary.tsv')

    rows = []
    seen = set()
    total = 0
    bad_length = 0
    with io.open(src, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip(NL).rstrip(chr(13))
            if not line.startswith('INSERT INTO `word` VALUES'):
                continue
            m = ROW.match(line)
            if m is None:
                sys.stderr.write('unparsable row: %s\n' % line[:120])
                return 1
            total += 1
            word = unquote(m.group(2))
            declared = int(m.group(3))
            frequency = int(m.group(4))
            if len(word) != declared:
                bad_length += 1
            if frequency <= FREQUENCY_BOUND:
                continue
            if word in seen:
                sys.stderr.write('duplicate word: %s\n' % word)
                return 1
            seen.add(word)
            rows.append((word, frequency))

    if bad_length:
        sys.stderr.write('%d rows whose length column is not the string '
                         'length; the loader derives length, so fix this '
                         'before trusting the output\n' % bad_length)
        return 1

    # Sorted by code point. The order is free -- a word is in the dictionary
    # or it is not, duplicates do not exist, and the BK tree's shape does not
    # change which words a search returns -- so sort for the one thing order
    # does buy: neighbouring words share prefixes, which is what makes the
    # packed form small, and the file diffs sanely when it is regenerated.
    rows.sort(key=lambda r: r[0])

    points = sum(len(w) for w, _ in rows)
    lo = min(ord(c) for w, _ in rows for c in w)
    hi = max(ord(c) for w, _ in rows for c in w)
    with io.open(out_path, 'w', encoding='utf-8', newline=NL) as f:
        f.write('# SPDX-License-Identifier: GPL-2.0-or-later' + NL)
        f.write('# generated by tools/extract_dictionary.py from the '
                'east-mod/ime SQL dump; do not edit' + NL)
        f.write('# the `word` table, frequency > %d '
                '(InputMethodService.FREQUENCY_BOUND)' % FREQUENCY_BOUND + NL)
        f.write('# %d of %d rows, %d code points, U+%04X..U+%04X' %
                (len(rows), total, points, lo, hi) + NL)
        f.write('# word' + TAB + 'frequency' + NL)
        for word, frequency in rows:
            f.write(word + TAB + str(frequency) + NL)

    print('%s: %d words of %d rows, %d code points, U+%04X..U+%04X'
          % (out_path, len(rows), total, points, lo, hi))
    return 0


if __name__ == '__main__':
    sys.exit(main())
